	template <typename CharArray>
	juce::String utf8EncodedCharArrayToString(const CharArray& charArray)
	{
		return {juce::CharPointer_UTF8(&charArray[0]), std::size(charArray)};
	}

	// Keeps at most maxContentBytes of a UTF-8 string, without cutting a multi-byte character in half.
	// When the text was shortened, a marker with the original size is appended after the kept content,
	// so the returned string can be longer than maxContentBytes.
	inline std::string truncateUtf8(const std::string& text, std::size_t maxContentBytes)
	{
		if(text.size() <= maxContentBytes)
			return text;

		auto end = maxContentBytes;

		// Continuation bytes have the form 10xxxxxx. If the first excluded byte is one, we would split a character.
		while(end > 0 && (static_cast<unsigned char>(text[end]) & 0xC0) == 0x80)
			--end;

		return text.substr(0, end) + "... [truncated, " + std::to_string(text.size()) + " bytes total]";
	}

	inline std::vector<juce::String> splitDoubleNullTerminatedString(const std::vector<char>& buffer)
	{
		std::vector<juce::String> stringArray;

		std::vector<char> tempBuffer;
		for(const char character : buffer)
		{
			if(character != '\0')
				tempBuffer.push_back(character);
			else if(!tempBuffer.empty())
			{
				stringArray.push_back(utf8EncodedCharArrayToString(tempBuffer));
				tempBuffer.clear();
			}
			else
				break;
		}

		return stringArray;
	}

	inline std::vector<char> createDoubleNullTerminatedStringBuffer(const std::vector<juce::String>& strings)
	{
		std::vector<char> rv;

		if(constexpr bool minimizeAllocations = true)
		{
			std::size_t size = strings.empty() ? 2 : 1;
			std::for_each(strings.cbegin(), strings.cend(), [&size](const juce::String& string)
				{
					auto s = string.length();
					size += s + (s ? 1 : 0);
				});
			rv.reserve(size);
		}

		std::for_each(strings.cbegin(), strings.cend(), [&rv](const juce::String& s)
			{
				if(s.isEmpty())
					return;

				for(const auto& c : s)
					rv.push_back(c);

				rv.push_back('\0');
			});

		if(strings.empty())
			rv.push_back('\0');

		rv.push_back('\0');
		return rv;
	}

	inline juce::String getWwiseObjectType(const juce::String& text)
	{
		int openBracket = text.indexOfChar('<');
		int closeBracket = text.indexOfChar(openBracket, '>');

		if(openBracket == 0 && closeBracket != -1)
			return text.substring(openBracket, closeBracket + 1);

		return {};
	}

	// It helps to understand this function with an example in mind.
	// Pattern:
	//		"\\Containers\\Default Work Unit\\<Actor-Mixer>$folders\\<Sound SFX>$track"
	// One item from the itemList (as generated by Reaper's ResolveRenderPattern()):
	//		"\Containers\Default Work Unit\<Actor-Mixer>Main SFX\Glass Random\<Sound SFX>DOORSlid_Glass Shower Door Sliding 1.wav"
	inline void extendFoldersObjectType(const juce::String& pattern, std::vector<juce::String>& itemList)
	{
		struct PrefixInfo
		{
			juce::String text;
			bool isFolders;
		};
		std::vector<PrefixInfo> patternPrefixes;
		juce::StringArray patternTokens = juce::StringArray::fromTokens(pattern, "\\", "");

		// Due to pattern expansion, we cannot traverse the pattern string at the same rate as the item strings.
		// Instead we build a vector of all prefixes in the pattern and will refer to it as we go through the items.
		for(const auto& token : patternTokens)
		{
			if(token.matchesWildcard("<*>*", false))
			{
				PrefixInfo info;
				info.text = getWwiseObjectType(token);
				info.isFolders = token.contains("$folders");
				patternPrefixes.push_back(info);
			}
		}

		// Process each rendered path.
		for(juce::String& item : itemList)
		{
			juce::StringArray itemParts = juce::StringArray::fromTokens(item, "\\", "");
			juce::String activePrefix = "";
			size_t prefIdx = 0;

			for(int k = 0; k < itemParts.size(); ++k)
			{
				juce::String& part = itemParts.getReference(k);

				// Does this part have a Wwise object type?
				if(part.matchesWildcard("<*>*", false))
				{
					juce::String partPrefix = getWwiseObjectType(part);

					// Does this align with the next expected prefix from our pattern?
					if(prefIdx < patternPrefixes.size() && partPrefix == patternPrefixes[prefIdx].text)
					{
						if(patternPrefixes[prefIdx].isFolders)
							activePrefix = patternPrefixes[prefIdx].text;
						else
							activePrefix = "";

						prefIdx++;
					}
					else
					{
						activePrefix = ""; // Hit an unexpected object type, stop propagating.
					}
				}
				else if(activePrefix.isNotEmpty())
				{
					// We have a prefix to apply and this part does not already have one. Apply the active prefix!
					part = activePrefix + part;
				}
			}

			item = itemParts.joinIntoString("\\");
		}
	}
